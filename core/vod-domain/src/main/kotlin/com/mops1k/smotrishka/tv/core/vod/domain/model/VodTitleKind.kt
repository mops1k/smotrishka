package com.mops1k.smotrishka.tv.core.vod.domain.model

/**
 * Вид карточки медиатеки — определяется порталом.
 *
 * `STREAM` можно запускать сразу: адрес потока уже есть в списке. `MULTISTREAM` требует
 * запроса карточки, потому что скрывает либо серии сериала, либо варианты качества фильма.
 */
enum class VodTitleKind {

    /** Одиночный поток: фильм, передача, запись матча. */
    STREAM,

    /** Несколько потоков: серии сезона или варианты одного фильма. */
    MULTISTREAM,
}
