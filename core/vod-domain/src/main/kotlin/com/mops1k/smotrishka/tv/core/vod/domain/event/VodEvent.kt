package com.mops1k.smotrishka.tv.core.vod.domain.event

/**
 * Доменное событие медиатеки.
 *
 * События публикуются после того, как состояние уже сохранено (избранное и прогресс — в Room),
 * и служат только уведомлением для подписчиков: подписаться и восстановить состояние можно
 * и без них.
 */
sealed interface VodEvent {

    /** Момент события в миллисекундах эпохи. */
    val occurredAtMillis: Long
}
