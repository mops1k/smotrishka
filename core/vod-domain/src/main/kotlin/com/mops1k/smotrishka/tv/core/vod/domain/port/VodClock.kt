package com.mops1k.smotrishka.tv.core.vod.domain.port

/**
 * Источник текущего времени для домена.
 *
 * Нужен, чтобы события избранного и прогресса получали время, а тесты могли его подменить
 * без системных часов.
 */
fun interface VodClock {

    /** Текущий момент в миллисекундах эпохи. */
    fun nowMillis(): Long
}
