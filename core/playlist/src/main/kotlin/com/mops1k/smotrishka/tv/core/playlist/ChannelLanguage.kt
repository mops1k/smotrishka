package com.mops1k.smotrishka.tv.core.playlist

import java.util.Locale

/**
 * Определение языка канала по признакам плейлиста.
 *
 * Порядок признаков (решение Александра 09.11.2026): явная метка `tvg-language`, затем
 * языковая группа канала, затем хвост имени канала (`... HD ES`, `... US`).
 *
 * Канал без признаков получает `null` — «без метки». Такие каналы в списках показываются
 * всегда, чтобы фильтр по языку не терял каналы.
 */
object ChannelLanguage {

    /** Языковые группы плейлиста: нормализованное название → язык. */
    private val GROUPS = mapOf(
        "казахский" to "Казахский",
        "казакша" to "Казахский",
        "қазақша" to "Казахский",
        "казахстан" to "Казахский",
        "kz" to "Казахский",
        "kz-казахский" to "Казахский",
        "украинский" to "Украинский",
        "украинские" to "Украинский",
        "українські" to "Украинский",
        "українська" to "Украинский",
        "ukraine" to "Украинский",
        "ua" to "Украинский",
        "белорусский" to "Белорусский",
        "беларускія" to "Белорусский",
        "by" to "Белорусский",
        "английский" to "Английский",
        "english" to "Английский",
        "usa" to "Английский",
        "us" to "Английский",
        "русский" to "Русский",
        "русские" to "Русский",
        "ru" to "Русский",
    )

    /** Языковые хвосты в имени канала: используются только при включённой настройке. */
    private val SUFFIXES = mapOf(
        "RU" to "Русский",
        "ES" to "Испанский",
        "US" to "Английский",
        "KZ" to "Казахский",
        "UA" to "Украинский",
        "BY" to "Белорусский",
        "FR" to "Французский",
        "DE" to "Немецкий",
        "TR" to "Турецкий",
        "PL" to "Польский",
    )

    /**
     * Возвращает язык канала.
     *
     * Порядок: явная метка `tvg-language`, затем языковая группа. Хвост имени (`... ES`,
     * `... US`) учитывается только при включённой настройке `byName` — у взрослых каналов
     * хвосты есть, но язык там не важен (решение Александра 09.11.2026).
     *
     * @param tvgLanguage значение атрибута `tvg-language`, если он есть в плейлисте;
     * @param group название группы (категории) канала;
     * @param name имя канала из плейлиста;
     * @param byName определять язык по названию канала (настройка, по умолчанию выключена);
     * @return язык канала или `null`, если язык не определён.
     */
    fun resolve(tvgLanguage: String?, group: String?, name: String, byName: Boolean = false): String? {
        tvgLanguage?.trim()?.takeIf(String::isNotEmpty)?.let { return it }
        // Группа разбирается классификатором: он отличает языковые категории от тематических.
        CategoryLanguage.resolve(group)?.let { return it }
        if (!byName) return null
        val tail = name.trim().split(' ').lastOrNull()?.uppercase(Locale.ROOT).orEmpty()
        return SUFFIXES[tail]
    }
}
