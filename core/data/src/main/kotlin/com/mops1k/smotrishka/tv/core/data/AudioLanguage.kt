package com.mops1k.smotrishka.tv.core.data

/**
 * Язык звуковой дорожки по умолчанию.
 *
 * У части каналов несколько дорожек (русская, английская, оригинальная). Русская выбирается
 * по умолчанию, но пользователь может это изменить.
 *
 * @param code языковой код для Media3, `null` — без предпочтения («оригинал»).
 */
enum class AudioLanguage(val code: String?) {
    /** Русская дорожка. */
    RUSSIAN("ru"),

    /** Английская дорожка. */
    ENGLISH("en"),

    /** Как отдал провайдер: дорожку не переключаем. */
    ORIGINAL(null),
}
