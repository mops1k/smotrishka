package com.mops1k.smotrishka.tv.core.data

/**
 * Режим отображения кадра.
 *
 * Широковещательные каналы часто приходят с пропорциями, отличными от экрана: кто-то хочет
 * видеть картинку целиком, кто-то — растянуть на весь экран, кто-то — обрезать поля.
 */
enum class AspectMode {
    /** Вписать целиком, с полосами по краям (по умолчанию). */
    FIT,

    /** Растянуть на весь экран, искажая пропорции. */
    STRETCH,

    /** Заполнить экран с обрезкой краёв. */
    CROP,

    /** Показывать в исходных пропорциях 1:1. */
    ORIGINAL,
}
