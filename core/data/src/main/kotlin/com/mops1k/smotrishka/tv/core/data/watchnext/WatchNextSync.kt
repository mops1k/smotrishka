package com.mops1k.smotrishka.tv.core.data.watchnext

/**
 * Публикация ленты «Сейчас идёт» на домашнем экране Android TV.
 *
 * Реализация зависит от платформы (TvProvider), поэтому вызывающий код работает
 * с интерфейсом: на телефонах и в тестах он заменяется реализацией без побочных эффектов.
 */
interface WatchNextSync {

    /**
     * Заменяет содержимое ленты.
     *
     * Список всегда заменяется целиком: карточки удалённых каналов не должны оставаться
     * на домашнем экране после обновления каталога.
     *
     * @param cards карточки в порядке показа; пустой список удаляет канал из лаунчера.
     */
    suspend fun publish(cards: List<WatchNextCard>)

    /** Убирает ленту из лаунчера: функционал выключен или источник не настроен. */
    suspend fun clear()
}
