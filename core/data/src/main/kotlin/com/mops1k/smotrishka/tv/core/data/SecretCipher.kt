package com.mops1k.smotrishka.tv.core.data

/**
 * Симметричное шифрование секретов источника (пароли, коды, токены).
 *
 * Отдельный интерфейс нужен, чтобы хранилище секретов тестировалось без Android Keystore,
 * а алгоритм шифрования проверялся отдельно от способа хранения ключа.
 */
interface SecretCipher {

    /** Шифрует строку; повторное шифрование того же текста даёт разный результат. */
    fun encrypt(plaintext: String): String

    /** Расшифровывает; `null` — данные повреждены или ключ не тот. */
    fun decrypt(payload: String): String?
}
