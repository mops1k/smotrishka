package com.mops1k.smotrishka.tv.core.data

/**
 * Качество видео, которое разрешено плееру.
 *
 * На слабом интернете ограничение экономит трафик и уменьшает буферизацию: плеер не пытается
 * тянуть 1080p, если канал это позволяет, а сеть — нет.
 */
enum class VideoQuality {
    /** Без ограничений: плеер сам выбирает по скорости сети. */
    AUTO,

    /** Не выше 360p — для очень слабого интернета. */
    SD_360,

    /** Не выше 480p. */
    SD_480,

    /** Не выше 720p. */
    HD,

    /** Не выше 1080p. */
    FULL_HD,
}
