package com.mops1k.smotrishka.tv.ui.home

/**
 * Расчёт позиции прокрутки, при которой фокусная строка списка стоит в середине видимой области.
 *
 * При листании пультом фокус остаётся в центре, а список прокручивается под ним: так строка
 * не «прилипает» к краю и видно следующие каналы. Одно и то же правило работает в списке
 * каналов, «Избранном» и отфильтрованном по запросу списке.
 */
object ListCentering {

    /**
     * Индекс строки, на которую нужно прокрутить список.
     *
     * @param focusedIndex индекс фокусной строки, отрицательный — фокуса в списке нет;
     * @param visibleRows сколько строк видно одновременно; 0 и меньше — считаем одну строку;
     * @return индекс первой видимой строки или `null`, если центрировать нечего.
     */
    fun targetIndex(focusedIndex: Int, visibleRows: Int): Int? {
        if (focusedIndex < 0) return null
        val rows = visibleRows.coerceAtLeast(1)
        return (focusedIndex - rows / 2).coerceAtLeast(0)
    }
}
