package com.mops1k.smotrishka.tv.ui.home

/**
 * Политика живого превью на главном экране.
 *
 * Базовая карточка показывает статичный визуал из макета; живое превью (без звука) включается
 * везде, где пользователь не выключил его экономией трафика. Раньше на ТВ и малопамятных
 * устройствах превью отключалось ради декодера, но на приставке t950s_be311 оно работало и
 * оказалось нужным (указание Александра 05.11.2026: вернуть живое превью).
 */
object PreviewPolicy {

    /**
     * Считать ли устройство телевизором.
     *
     * Оставлено для настроек и отчётов: на показ превью признак больше не влияет.
     *
     * @param hasLeanback объявлена ли возможность Leanback;
     * @param isLowRam малопамятное ли устройство.
     */
    fun isTelevision(hasLeanback: Boolean, isLowRam: Boolean): Boolean = hasLeanback || isLowRam

    /**
     * Показывать ли живое превью.
     *
     * На малопамятных устройствах живое превью выключено: у приставки t950s_be311 один
     * аппаратный HEVC-декодер, превью его занимало, и канал в HEVC не запускался
     * (`Failed to initialize decoder: c2.amlogic.hevc.decoder`, 05.11.2026).
     *
     * @param isTv устройство считается телевизором (на превью не влияет);
     * @param isLowRam малопамятное ли устройство: там превью статичное;
     * @param dataSaver включена ли экономия трафика: она гасит превью на любом устройстве.
     */
    fun showLive(isTv: Boolean, isLowRam: Boolean, dataSaver: Boolean = false): Boolean =
        !dataSaver && !isLowRam
}
