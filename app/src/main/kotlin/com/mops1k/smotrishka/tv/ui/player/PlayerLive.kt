package com.mops1k.smotrishka.tv.ui.player

import androidx.media3.common.MediaItem

/**
 * Элемент воспроизведения для живого потока провайдера.
 *
 * Раньше здесь задавалась принудительная live-конфигурация: отступ 8 секунд от живого края
 * и скорости догоняния 0.97–1.05. На ТВ-приставке `t950s_be311` это дало обратный эффект:
 * провайдер отдаёт конечное окно (около 40 секунд) и помечает его живым, позиция уходила
 * в минус (`mediaPos=-39.85`), плеер бесконечно переискивал и кадра не было вообще.
 * Сторонний плеер (OTT Play) играет эти же потоки без таких подсказок, поэтому конфигурацию
 * больше не навязываем: Media3 сам определяет живой край по манифесту.
 */
object PlayerLive {

    /**
     * Собирает элемент потока без принудительного живого режима.
     *
     * @param url адрес потока.
     */
    fun mediaItem(url: String): MediaItem = MediaItem.fromUri(url)
}
